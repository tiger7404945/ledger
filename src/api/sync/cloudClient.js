/**
 * 云端客户端契约（只有形状，没有实现）
 * ------------------------------------------------------------
 * 这个文件里一行逻辑都没有，它存在的唯一目的是把「同步引擎需要云端提供什么」
 * 固定下来。有了它：
 *
 *   - S2 的 fakeCloud 与 S3 的 cloudbaseAdapter 实现的是**同一套接口**，
 *     所以 S3 接真云端时，syncEngine 一行都不用改；
 *   - 调 bug 时可以先用假云端跑通调度逻辑，不用怀疑网络。
 *
 * 三个方法，语义如下：
 *
 *   pull(collection, { since, cursor, limit, ids })
 *     拉取增量。
 *     - since  —— 水位线：只要 updatedAt 严格大于它的文档（首次同步传 0）
 *     - cursor —— 游标：上一次返回的 cursor，为 null 表示从头开始
 *     - limit  —— 单页条数上限（云端有行数限制，必须分页）
 *     - ids    —— 精确拉取指定 **本地 id**（用于「推送被拒后把云端版本拉回来」）
 *     返回 { docs, serverTime, hasMore, cursor }
 *     **docs 里必须带 updatedAt**，合并规则完全依赖它。
 *
 *   push(collection, docs, options?)
 *     **条件 upsert**：只有当本地这份不旧于云端时才覆盖。
 *     幂等键是云端 `_id`，所以重复推送不会产生重复文档。
 *     返回 { upserted: string[], rejected: [{ id, cloudUpdatedAt }], stamps }
 *     `upserted` 与 `rejected[].id` 都是**本地 id**（引擎拿它们去清队列）。
 *
 *     `stamps`（S4-6）—— `{ [本地id]: 服务端刻度 }`，本次**真正写成功**的文档
 *     被服务端盖上的裁决刻度。引擎拿它写回本地副本（`store.applyStamps`），
 *     这样写者自己也持有一个与本地时钟无关的版本时间，跨设备裁决才落在同一条
 *     时间轴上（否则要等下一轮 pull 才拿到，白等一个周期）。
 *
 *     ⚠️ **`stamps` 的 key 必须是「本地 id」**，与 `upserted` 同一套 id 空间。
 *        这条特别容易写错：真实适配器是**按云端别名**去问云函数的，云函数也按
 *        别名回报 —— 顺手把那份别名当 key 交出去，消费方 `applyStamps` 按本地 id
 *        查文档就会**每条都 miss**。而它是**静默**的（查不到就跳过、不抛错），
 *        单设备与全部测试都测不出来（`fakeCloud` 按本地 id 分桶，天然不会错）。
 *
 *     ⚠️ `stamps` 允许缺省或为空对象 —— 云函数未部署 / 网关不通时静默降级。
 *        适配器**不能因此抛错**，否则「能推的数据」会被一个可选增强搞成「同步失败」。
 *
 *     `options.clockOffset`（S4-2）—— 本地时钟偏差 = 服务端时间 - 本地时间。
 *     适配器比较「本地 vs 云端」时给本地那份加上它，把两边换算到服务端时间轴。
 *     只在服务端时间**可信**（`serverTime().source === 'cloud-function'`）时
 *     引擎才传非 0 值；否则传 0，退回纯客户端时钟比较。
 *     没有这个校正，**慢时钟的设备会把自己刚写的新数据判成「比云端旧」而放弃推送**。
 *
 *     ⚠️ rejected 这个字段是关键。如果云端因为「你这份更旧」而拒绝，
 *     却不把这件事告诉客户端，客户端会以为自己推成功了、云端还停在旧版本，
 *     两端就此分叉 —— 这个 bug 在单设备上测不出来，要等真的两台设备才暴露。
 *
 * 关于错误：适配器抛错时**应该**给错误对象打一个 `kind` 标记
 *   （取值见 `sync/errors.js` 的 `SYNC_ERROR_KIND`），引擎据此分类处置 ——
 *   比如「登录态失效」要重新登录而不是退避重试。
 *   不打标记也能工作（引擎会按错误码嗅探），但打标记更准。
 *
 * 关于 id：**契约层面一律用「本地 id」**（文档的 `id` 字段）。
 *   云端内部把 `_id` 做成什么形状是**实现细节**，不该泄漏到这里。
 *   CloudBase 的 `_id` 在集合内跨账号全局唯一、而 PRIVATE 权限按 `_openid`
 *   隔离读，两者错位会导致换身份后 `E11000`（S4-7）；该适配器的解法是把
 *   `_id` 换成 `<账号前缀>_<本地 id>` 的别名，但那是它自己的事 ——
 *   `fakeCloud` 就用不着，它本来就是按 `_openid` 分桶的。
 *   无论哪种实现，`pull()` 回来的文档都必须能被 `core/merge.js` 的
 *   `fromRemote()` 还原出本地 id（靠业务字段 `id`）。
 *
 *   serverTime()
 *     服务端当前时间。用来做两件事：写水位线、以及在不信任客户端时钟时充当
 *     冲突裁决依据（S4-2）。
 *
 *     返回 `{ value: <毫秒时间戳>, source: <来源标记> }`，**不是裸数字**。
 *     `source` 让调用方能判断这个时间可不可信：
 *       - `'cloud-function'` —— 云函数返回的真服务端时钟，**可做裁决**；
 *       - `'watermark-lower-bound'` —— 降级取「能观察到的最新 `_serverTs`」，
 *         是**下界**：当水位线安全，**不能做裁决**。
 *
 *     为什么要区分：CloudBase Web SDK 没有「读服务端当前时间」的接口，
 *     真值必须来自云函数。云函数不可用时不能让同步整个失败，所以降级 ——
 *     但降级后的值不足以支撑「谁更新」的判断，必须让调用方知道。
 *
 *     ⚠️ 注意与 `pull()` 返回值里的 `serverTime` **不是一回事**：
 *     那个是「本页拉到的最大 `_serverTs`」，用于推进水位线，始终是数字。
 *     两者同名纯属历史巧合，改动时别搞混。
 *
 * 归属与权限：
 *   云开发会自动给带登录态的写入注入 `_openid`，读取时也由**安全规则**
 *   在服务端过滤。客户端不要自己维护这个字段，更不要试图用前端代码
 *   「过滤掉别人的数据」—— 客户端代码谁都能改。
 */

/** 单页默认条数（云端单次查询有行数上限，别一次要太多） */
export const CLOUD_PAGE_LIMIT = 100

export const CLOUD_METHODS = ['pull', 'push', 'serverTime']

/**
 * 检查一个对象是否长得像云端客户端。
 * 在装配处调用，能把「接口没对齐」这类错误在启动时就暴露出来，
 * 而不是等到第一次同步才炸。
 */
export function assertCloudClient(client) {
  if (!client) return false
  const missing = CLOUD_METHODS.filter((m) => typeof client[m] !== 'function')
  if (missing.length) {
    throw new Error(`[ledger] 云端客户端缺少方法：${missing.join(', ')}（见 sync/cloudClient.js）`)
  }
  return true
}
